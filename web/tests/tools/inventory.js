// List every registered part and write docs/component-test-coverage.md
//
//   node web/tests/tools/inventory.js          (from the repo root)
//   node tests/tools/inventory.js              (from web/)
'use strict';
const fs = require('fs');
const path = require('path');
const { WEB, REPO, Parts: P, Bom: B, allTypes } = require('./load-parts');

function testFiles() {
  const dir = path.join(WEB, 'tests');
  return fs.readdirSync(dir).filter((f) => f.endsWith('.test.js')).sort()
    .map((f) => ({ name: f, text: fs.readFileSync(path.join(dir, f), 'utf8') }));
}

function mentions(text, type) {
  const re = new RegExp('([\'"`])' + type.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\1');
  return re.test(text);
}

function pinNames(type) {
  const d = P.T[type];
  const p = { id: 'INV', type, x: 0, y: 0, rot: 0, props: JSON.parse(JSON.stringify(d.props || {})) };
  try {
    const pins = d.pins ? d.pins(p) || [] : [];
    return { ok: true, names: pins.map((q) => q && q.name), err: '' };
  } catch (e) {
    return { ok: false, names: [], err: e.message };
  }
}

function collect() {
  const tests = testFiles();
  const types = allTypes();
  const rows = [];
  for (const type of types) {
    const d = P.T[type];
    const pins = pinNames(type);
    const props = d.props || {};
    const edit = d.edit || [];
    const mentioned = tests.filter((t) => mentions(t.text, type)).map((t) => t.name);
    const namedInHandWritten = mentioned.filter((n) => n !== 'parts_all.test.js' && n !== 'parts_props.test.js' && n !== 'parts_behavior.test.js');
    // The data-driven suite loops over allTypes() and so covers every type even
    // when the type name is not a string literal in the file.
    for (const auto of ['parts_all.test.js', 'parts_props.test.js']) {
      if (!mentioned.includes(auto)) mentioned.push(auto);
    }
    mentioned.sort();
    rows.push({
      type,
      label: d.label || '',
      cat: d.cat || '',
      pinCount: pins.names.length,
      pinNames: pins.names,
      pinErr: pins.err,
      props,
      edit,
      stamp: typeof d.stamp === 'function',
      tick: typeof d.tick === 'function',
      espStep: typeof d.espStep === 'function',
      svg: typeof d.svg === 'function',
      readout: typeof d.readout === 'function',
      measure: typeof d.measure === 'function',
      interactive: !!d.interactive,
      bom: !!(B.CATALOG && B.CATALOG[type]),
      tests: mentioned,
      namedInHandWritten,
    });
  }
  return { types: rows, testFileCount: tests.length };
}

function mdEscape(s) {
  return String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function propsCell(row) {
  const p = row.props || {};
  const keys = Object.keys(p);
  if (!keys.length) return '—';
  return keys.map((k) => {
    const v = p[k];
    if (Array.isArray(v)) return k + '=[' + v.join(', ') + ']';
    return k + '=' + JSON.stringify(v);
  }).join(', ');
}

function editCell(row) {
  if (!row.edit.length) return '—';
  return row.edit.map((e) => {
    let s = e.k + ':' + (e.t || '');
    if (e.t === 'range') s += '[' + e.min + '…' + e.max + ']';
    if (e.opts) s += '(' + e.opts.join(', ') + ')';
    return s;
  }).join(', ');
}

function pinCell(row) {
  if (row.pinErr) return 'ERROR: ' + row.pinErr;
  if (row.pinCount > 24) return String(row.pinCount) + ' pins';
  if (!row.pinCount) return '0';
  return String(row.pinCount) + ' (' + row.pinNames.join(', ') + ')';
}

function behaviorCell(row) {
  const bits = [];
  if (row.stamp) bits.push('stamp');
  if (row.tick) bits.push('tick');
  if (row.espStep) bits.push('espStep');
  if (row.measure) bits.push('measure');
  if (row.readout) bits.push('readout');
  if (row.interactive) bits.push('interactive');
  return bits.length ? bits.join(', ') : '—';
}

function render(data) {
  const rows = data.types;
  const untested = rows.filter((r) => !(r.namedInHandWritten && r.namedInHandWritten.length));
  const noBom = rows.filter((r) => !r.bom);
  const noStamp = rows.filter((r) => !r.stamp);
  const lines = [];
  lines.push('# Component test coverage');
  lines.push('');
  lines.push('Generated by `node web/tests/tools/inventory.js`. Do not edit by hand; re-run the script after adding parts.');
  lines.push('');
  lines.push('- Registered part types: **' + rows.length + '**');
  lines.push('- Existing `web/tests/*.test.js` files scanned: **' + data.testFileCount + '**');
  lines.push('- Types with a `stamp()` circuit model: **' + rows.filter((r) => r.stamp).length + '** (' + noStamp.length + ' without: ' + noStamp.map((r) => r.type).join(', ') + ')');
  lines.push('- Types with a BOM catalog entry: **' + rows.filter((r) => r.bom).length + '** (' + noBom.length + ' without: ' + noBom.map((r) => r.type).join(', ') + ')');
  lines.push('- Types never named as a string literal in an older hand-written test: **' + untested.length + '**' + (untested.length ? ' (' + untested.map((r) => r.type).join(', ') + ')' : ''));
  lines.push('');
  lines.push('Every type is covered by the data-driven suite (`web/tests/parts_all.test.js` instantiates, draws, netlists, schematizes and simulates each one; `parts_props.test.js` sweeps every scalar property). A named mention in an older test is not required for that coverage. `parts_behavior.test.js` adds known-answer checks for the key analog parts.');
  lines.push('');
  lines.push('3D rendering (`js/view3d.js`) is not exercised here: it needs a browser, WebGL and THREE.js.');
  lines.push('');
  lines.push('## Parts');
  lines.push('');
  lines.push('| Type | Label | Category | Pins | Default props | Editable properties | Sim behavior | BOM | Existing tests |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const r of rows) {
    lines.push('| ' + [
      '`' + r.type + '`',
      mdEscape(r.label),
      mdEscape(r.cat),
      mdEscape(pinCell(r)),
      mdEscape(propsCell(r)),
      mdEscape(editCell(r)),
      mdEscape(behaviorCell(r)),
      r.bom ? 'yes' : '—',
      r.tests.length ? r.tests.map((t) => '`' + t + '`').join(', ') : '—',
    ].join(' | ') + ' |');
  }
  lines.push('');
  return lines.join('\n');
}

function writeDoc(data) {
  const dest = path.join(REPO, 'docs/component-test-coverage.md');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, render(data));
  return dest;
}

if (require.main === module) {
  const data = collect();
  const dest = writeDoc(data);
  const untested = data.types.filter((r) => !(r.namedInHandWritten && r.namedInHandWritten.length)).map((r) => r.type);
  console.log('parts', data.types.length);
  console.log('untested mentions', untested.length, untested.join(' '));
  console.log('wrote', dest);
}

module.exports = { collect, render, writeDoc, mentions, testFiles };
